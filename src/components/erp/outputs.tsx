"use client";

import type { ReactNode } from "react";
import { Printer, X } from "lucide-react";
import { BohMark } from "@/components/brand/boh-logo";
import { Modal } from "@/components/erp/ui";
import { formatDate, formatMoney, partNumber, projectRecords, revisionLabel, type ErpState } from "@/lib/erp/model";

export type OutputKind = "po" | "production" | "inspection" | "dispatch" | "invoice";

export const OUTPUT_LABELS: Record<OutputKind, string> = {
  po: "Purchase order summary",
  production: "Production order",
  inspection: "Inspection report",
  dispatch: "Dispatch note",
  invoice: "Customer invoice",
};

/** Whether an output can be generated yet, and why not. */
export function outputAvailability(state: ErpState, projectId: string, kind: OutputKind): { ok: boolean; reason: string } {
  const records = projectRecords(state, projectId);
  switch (kind) {
    case "po": return { ok: records.purchaseOrders.length > 0, reason: "No purchase order" };
    case "production": return { ok: records.productionOrders.length > 0, reason: "No production order yet" };
    case "inspection": return { ok: records.inspectionReports.length > 0, reason: "Generate the report in Quality" };
    case "dispatch": return { ok: records.dispatches.length > 0, reason: "Available after dispatch" };
    case "invoice": return { ok: records.invoices.length > 0, reason: "Available after invoicing" };
  }
}

function Meta({ items }: { items: [string, ReactNode][] }) {
  return <div className="erp-doc-meta">{items.map(([label, value]) => <div key={label}><small>{label}</small><b>{value}</b></div>)}</div>;
}

function DocFrame({ title, number, children }: { title: string; number: string; children: ReactNode }) {
  return <article className="erp-doc erp-print">
    <div className="erp-doc-top">
      <div className="erp-doc-brand"><BohMark size={30} /><span><b>BOH</b> ERP</span></div>
      <div className="erp-doc-title"><h1>{title}</h1><span>{number}</span></div>
    </div>
    <span className="erp-doc-stamp">ILLUSTRATIVE DEMO DOCUMENT · FICTIONAL DATA · NOT A VALID COMMERCIAL DOCUMENT</span>
    {children}
    <p className="erp-doc-foot">Generated by the BOH ERP demo from the project record. Every value on this document was entered once in the project and reused here.</p>
  </article>;
}

export function OutputDocument({ state, projectId, kind, productionOrderId }: { state: ErpState; projectId: string; kind: OutputKind; productionOrderId?: string }) {
  const records = projectRecords(state, projectId);
  const { project, customer } = records;
  const po = records.purchaseOrders[0];
  if (!project || !customer || !po) return <p>Record not available.</p>;
  const currency = po.currency;
  const projectLabel = `${project.code} · ${project.name}`;

  if (kind === "po") {
    const lines = records.lineItems;
    const priced = lines.every((line) => line.unitPrice !== null);
    return <DocFrame title="Purchase order summary" number={po.number}>
      <Meta items={[["Customer", customer.name], ["Project", projectLabel], ["Contact", customer.contact || "—"], ["PO date", formatDate(po.poDate)], ["Required delivery", formatDate(po.deliveryDate)], ["Currency", currency]]} />
      <table><thead><tr><th>Part</th><th>Rev</th><th>Description</th><th className="r">Qty</th><th className="r">Unit price</th><th className="r">Amount</th></tr></thead><tbody>
        {lines.map((line) => { const part = state.parts.find((item) => item.id === line.partId); return <tr key={line.id}><td>{part?.number}</td><td>{revisionLabel(state, line.revisionId)}</td><td>{part?.description}</td><td className="r">{line.quantity} {line.unit}</td><td className="r">{line.unitPrice !== null ? formatMoney(line.unitPrice, currency) : "—"}</td><td className="r">{line.unitPrice !== null ? formatMoney(line.unitPrice * line.quantity, currency) : "—"}</td></tr>; })}
      </tbody><tfoot><tr><td colSpan={5}>Order value{priced ? "" : " (as stated on the PO)"}</td><td className="r">{po.value !== null ? formatMoney(po.value, currency) : "Not stated"}</td></tr></tfoot></table>
    </DocFrame>;
  }

  if (kind === "production") {
    const order = records.productionOrders.find((item) => item.id === productionOrderId) ?? records.productionOrders[0];
    if (!order) return <p>No production order yet.</p>;
    const part = state.parts.find((item) => item.id === order.partId);
    const docs = records.documents.filter((doc) => doc.partId === order.partId || doc.partId === null);
    const checks = records.inspectionRequirements.filter((req) => req.partId === order.partId || req.partId === null);
    const materials = records.materialRequirements.filter((req) => req.lineItemId === order.lineItemId || req.lineItemId === null);
    return <DocFrame title="Production order" number={order.number}>
      <Meta items={[["Project", projectLabel], ["Customer PO", po.number], ["Part", `${part?.number} rev ${revisionLabel(state, order.revisionId)}`], ["Description", part?.description ?? ""], ["Quantity", String(order.quantity)], ["Status", order.status]]} />
      <h3>Required documents</h3>
      <table><thead><tr><th>Number</th><th>Name</th><th>Type</th><th>Rev</th><th>Status</th></tr></thead><tbody>{docs.length ? docs.map((doc) => <tr key={doc.id}><td>{doc.number}</td><td>{doc.name}</td><td>{doc.type}</td><td>{doc.revision}</td><td>{doc.status}</td></tr>) : <tr><td colSpan={5}>No documents linked</td></tr>}</tbody></table>
      <h3 style={{ marginTop: 18 }}>Material</h3>
      <table><thead><tr><th>Material</th><th className="r">Quantity</th></tr></thead><tbody>{materials.length ? materials.map((req) => <tr key={req.id}><td>{req.material}</td><td className="r">{req.quantity} {req.unit}</td></tr>) : <tr><td colSpan={2}>No material requirement</td></tr>}</tbody></table>
      <h3 style={{ marginTop: 18 }}>Inspection requirements</h3>
      <table><thead><tr><th>Parameter</th><th>Specification</th><th>Acceptance</th></tr></thead><tbody>{checks.length ? checks.map((req) => <tr key={req.id}><td>{req.name}</td><td>{req.spec} {req.unit}</td><td>{req.acceptance || "—"}</td></tr>) : <tr><td colSpan={3}>None defined</td></tr>}</tbody></table>
      <div className="erp-doc-sign"><div>Released by (planning)</div><div>Completed by (production)</div></div>
    </DocFrame>;
  }

  if (kind === "inspection") {
    const report = records.inspectionReports[0];
    if (!report) return <p>No inspection report yet.</p>;
    return <DocFrame title="Inspection report" number={report.number}>
      <Meta items={[["Project", projectLabel], ["Customer PO", po.number], ["Date", formatDate(report.createdAt)], ["Production orders", records.productionOrders.map((order) => order.number).join(", ") || "—"], ["Parts", records.lineItems.map((line) => `${partNumber(state, line.partId)} rev ${revisionLabel(state, line.revisionId)}`).join(", ")], ["Overall result", report.passed ? "PASS" : "FAIL"]]} />
      <table><thead><tr><th>Parameter</th><th>Part</th><th>Specification</th><th>Acceptance</th><th>Result (illustrative)</th></tr></thead><tbody>
        {report.results.map((result) => { const req = state.inspectionRequirements.find((item) => item.id === result.requirementId); return <tr key={result.requirementId}><td>{req?.name}</td><td>{req?.partId ? partNumber(state, req.partId) : "Project"}</td><td>{req?.spec} {req?.unit}</td><td>{req?.acceptance || "—"}</td><td>{result.pass ? "PASS" : "FAIL"} · {result.observed}</td></tr>; })}
      </tbody></table>
      <p style={{ marginTop: 12, color: "#6B7280" }}>Results are generated for demonstration and do not represent real measurements.</p>
      <div className="erp-doc-sign"><div>Inspected by</div><div>Approved by (quality)</div></div>
    </DocFrame>;
  }

  if (kind === "dispatch") {
    const dispatch = records.dispatches[0];
    if (!dispatch) return <p>Not dispatched yet.</p>;
    return <DocFrame title="Dispatch note" number={dispatch.number}>
      <Meta items={[["Ship to", customer.name], ["Customer PO", po.number], ["Project", projectLabel], ["Dispatch date", formatDate(dispatch.dispatchedAt)], ["Required delivery", formatDate(po.deliveryDate)], ["Inspection report", records.inspectionReports[0]?.number ?? "—"]]} />
      <table><thead><tr><th>Part</th><th>Rev</th><th>Description</th><th className="r">Quantity</th></tr></thead><tbody>
        {records.lineItems.map((line) => { const part = state.parts.find((item) => item.id === line.partId); return <tr key={line.id}><td>{part?.number}</td><td>{revisionLabel(state, line.revisionId)}</td><td>{part?.description}</td><td className="r">{line.quantity} {line.unit}</td></tr>; })}
      </tbody></table>
      <div className="erp-doc-sign"><div>Packed by</div><div>Received by (customer)</div></div>
    </DocFrame>;
  }

  const invoice = records.invoices[0];
  if (!invoice) return <p>No invoice yet.</p>;
  return <DocFrame title="Invoice" number={invoice.number}>
    <Meta items={[["Bill to", customer.name], ["Customer PO", po.number], ["Project", projectLabel], ["Invoice date", formatDate(invoice.issuedAt)], ["Due date", formatDate(invoice.dueAt)], ["Delivery note", records.dispatches[0]?.number ?? "—"]]} />
    <table><thead><tr><th>Description</th><th className="r">Qty</th><th className="r">Unit price</th><th className="r">Amount</th></tr></thead><tbody>
      {invoice.lines.map((line) => <tr key={line.description}><td>{line.description}</td><td className="r">{line.quantity} {line.unit}</td><td className="r">{formatMoney(line.unitPrice, invoice.currency)}</td><td className="r">{formatMoney(line.amount, invoice.currency)}</td></tr>)}
    </tbody><tfoot>
      <tr><td colSpan={3}>Subtotal</td><td className="r">{formatMoney(invoice.subtotal, invoice.currency)}</td></tr>
      <tr><td colSpan={3}>Tax ({invoice.taxRate}%, demo setting)</td><td className="r">{formatMoney(invoice.tax, invoice.currency)}</td></tr>
      <tr><td colSpan={3}>Total</td><td className="r">{formatMoney(invoice.total, invoice.currency)}</td></tr>
    </tfoot></table>
    <p style={{ marginTop: 12, color: "#6B7280" }}>Illustrative invoice only. BOH ERP’s demo is not an accounting or tax-compliant invoicing system.</p>
  </DocFrame>;
}

export function OutputDialog({ state, projectId, kind, productionOrderId, onClose }: { state: ErpState; projectId: string; kind: OutputKind; productionOrderId?: string; onClose: () => void }) {
  return <Modal label={OUTPUT_LABELS[kind]} onClose={onClose} wide>
    <div className="erp-dialog-bar">
      <h2>{OUTPUT_LABELS[kind]}</h2>
      <div className="erp-head-actions">
        <button type="button" className="erp-btn erp-btn-sm" onClick={() => window.print()}><Printer size={14} /> Print / save as PDF</button>
        <button type="button" className="erp-btn erp-btn-ghost erp-btn-sm" onClick={onClose}><X size={14} /> Close</button>
      </div>
    </div>
    <OutputDocument state={state} projectId={projectId} kind={kind} productionOrderId={productionOrderId} />
  </Modal>;
}
